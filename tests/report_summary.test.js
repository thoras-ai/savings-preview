test('page one follows the levers and the fleet size', () => {
  const data = prepare('savings-preview.otlp.json');
  const base = run(data).r.totals.savings;
  const { r, st } = run(data, { headroom: 0.3, namespaces: ['shop'], clusters: 12, engineerCost: 100000 });
  assert.notStrictEqual(r.totals.savings, base);
  const html = summary.markup(data, r, st), out = text(html);
  for (const s of ['Target is 1.3 ×', 'Only the namespace shop is included.', summary.headline(summary.figures(r))]) assert.ok(out.includes(s), s);
  assert.ok(html.includes('value="12"'));
  assert.ok(out.includes(summary.engineers(r.totals.savings * 12, 100000)));
  assert.strictEqual(summary.engineers(41053, 200000), 'about 0.2 of a loaded engineer');
  assert.strictEqual(summary.engineers(330000, 200000), 'about 1.7 loaded engineers');
  assert.strictEqual(summary.engineers(5000, 200000), 'about 6 engineer-days');
});

test('a range or namespaces with no data shows one plain line', () => {
  const data = prepare('savings-preview.otlp.json');
  for (const patch of [{ range: [1, 2] }, { namespaces: ['nowhere'] }]) {
    const { r, st } = run(data, patch);
    const out = text(summary.markup(data, r, st));
    assert.ok(out.includes('No data in the selected time range or namespaces.'), out);
    assert.ok(!/1970|0 seconds|\$0 a year|–/.test(out), out);
  }
});

test('the cluster count lives in the link and leaves the figures alone', () => {
  const st = state.parse('#clusters=5');
  assert.strictEqual(st.clusters, 5);
  assert.strictEqual(state.serialize(st), 'clusters=5');
  assert.strictEqual(state.serialize(state.DEFAULTS), '');
  for (const bad of ['0', '-2', '1.5', 'x', '20000']) assert.strictEqual(state.parse('#clusters=' + bad).clusters, 1, bad);
  assert.strictEqual(state.affectsFigures(['clusters']), false);
});

test('the gap chart names requested today, with Thoras, usage and waste', () => {
  assert.deepStrictEqual(chart.legend('gap').map(i => i.name), ['Requested today', 'With Thoras', 'Usage', 'Waste']);
  const { r } = run(prepare('savings-preview.otlp.json'));
  const d = chart.downsample(r.series, chart.modes.gap);
  for (let i = 0; i < d.t.length; i++) {
    if (!isFinite(d.a[i])) continue;
    assert.ok(d.u[i] > 0 && d.b[i] <= d.a[i] + 1e-9, 'usage is priced and Thoras never requests more than today');
  }
});
