'use strict';
const test = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const path = require('node:path');
const model = require('../src/js/model.js');
const state = require('../src/js/state.js');
const chart = require('../src/js/chart.js');
const summary = require('../src/js/section-summary.js');

const DEMO = path.join(__dirname, '..', 'fixtures', 'demo-cluster.compact.otlp.json');

function prepare(name) {
  const file = path.isAbsolute(name) ? name : path.join(__dirname, '..', 'fixtures', name);
  return model.prepare(JSON.parse(fs.readFileSync(file, 'utf8')));
}

function run(data, patch = {}) {
  const st = Object.assign({}, state.DEFAULTS, patch);
  return { data, st, r: model.compute(data, state.levers(st)) };
}

const text = html => html.replace(/<[^>]+>/g, ' ').replace(/&amp;/g, '&').replace(/&#39;/g, "'").replace(/\s+/g, ' ');
const HEDGES = /~|[Pp]rovisional|fidelity|\btiers?\b|contract|series|snapshot|counted|resolution|held metrics|treat it as a direction|[Cc]onfidence/;

// The demo cluster is generated by `go run ./scripts/gen_demo`, which make test runs first.
test('the demo cluster reads $36,426 a year, 57%, with three named workloads', { skip: !fs.existsSync(DEMO) && 'run go run ./scripts/gen_demo first' }, () => {
  const { data, st, r } = run(prepare(DEMO));
  const fig = summary.figures(r);
  assert.strictEqual(summary.headline(fig), 'Thoras would cut this cluster’s compute spend by $36,426 a year, 57%.');
  assert.deepStrictEqual(summary.pick(r, st).map(w => w.name), ['storefront', 'nightly-etl', 'postgres-orders']);
  assert.strictEqual(summary.oomKilled(data, r, st), 2);
  const out = text(summary.markup(data, r, st));
  for (const s of [
    '$63,693 / yr', '$27,267 / yr', 'saves $36,426 57%', '149 cores · 465 GiB requested', '46 cores · 255 GiB requested',
    'From 14 days of your Prometheus data. Computed on your laptop. Nothing installed, nothing uploaded.', '2 workloads are being OOM-killed today.',
    'Clusters like this one', 'Book a demo', 'Copy summary'
  ]) assert.ok(out.includes(s), s);
  assert.ok(!out.includes('savings-preview run'), 'a 14-day file needs no longer run');
  assert.ok(!HEDGES.test(out), out.match(HEDGES));
});

test('today and with Thoras: requests less the waste, utilization weighted by price and never over 100%', () => {
  for (const name of ['savings-preview.otlp.json', 'minikube-poll.otlp.json']) {
    const { r } = run(prepare(name));
    const fig = summary.figures(r), t = r.totals;
    assert.strictEqual(fig.today.spend - fig.savings, fig.thoras.spend);
    assert.ok(Math.abs(fig.thoras.cores - (t.reqCores - t.cores)) < 1e-9);
    assert.ok(Math.abs(fig.thoras.gib - (t.reqGiB - t.gib)) < 1e-9);
    assert.ok(fig.today.utilization > 0 && fig.today.utilization < fig.thoras.utilization && fig.thoras.utilization <= 1, name);
  }
  // One workload at half its request, priced 2:1 CPU to memory.
  const w = { series: {}, reqCores: 2, reqGiB: 4, useCores: 1, useGiB: 1, wasteCores: 0.5, wasteGiB: 2 };
  const r = { pricing: { perCore: 2, perGiB: 1 }, workloads: [w, { series: null }] };
  assert.strictEqual(summary.utilization(r, false), (1 * 2 + 1 * 1) / (2 * 2 + 4 * 1));
  assert.strictEqual(summary.utilization(r, true), (1 * 2 + 1 * 1) / (1.5 * 2 + 2 * 1));
});

test('the picker takes the biggest all-day saver, a burst job and a right-sized workload', () => {
  const series = active => ({ useCost: Float64Array.from({ length: 100 }, (_, i) => (i < active ? 10 : 1)) });
  const wl = (name, spend, savings, active) => ({ id: 'ns/deployment/' + name, name, ns: 'ns', kind: 'deployment', series: series(active), annualSpend: spend, annualSavings: savings, savingsPct: spend ? savings / spend : 0 });
  const r = {
    fidelity: { snapshot: false, start: 0, end: 14 * 86400, spanSeconds: 14 * 86400 },
    workloads: [
      wl('api', 4000, 2000, 60), wl('web', 3000, 2500, 50), wl('etl', 5000, 4600, 10), wl('cron', 900, 880, 5),
      wl('db', 6000, 120, 55), wl('cache', 1000, 0, 55), wl('idle', 0, 0, 0)
    ]
  };
  assert.deepStrictEqual(summary.pick(r, state.DEFAULTS).map(w => w.name), ['web', 'etl', 'db']);
  // Under a day of data no workload counts as a burst job, and without a
  // right-sized workload the next biggest saver fills the row.
  const short = Object.assign({}, r, { fidelity: Object.assign({}, r.fidelity, { spanSeconds: 3600, end: 3600 }), workloads: r.workloads.filter(w => w.name !== 'db' && w.name !== 'cache') });
  assert.deepStrictEqual(summary.pick(short, state.DEFAULTS).map(w => w.name), ['etl', 'web', 'api']);
  // A right-sized workload spending under a tenth of the first pick is left out.
  const tiny = Object.assign({}, r, { workloads: r.workloads.map(w => (w.name === 'db' ? Object.assign({}, w, { annualSpend: 300, annualSavings: 6, savingsPct: 0.02 }) : w)) });
  assert.deepStrictEqual(summary.pick(tiny, state.DEFAULTS).map(w => w.name), ['web', 'etl', 'cache']);
  assert.deepStrictEqual(summary.pick(run(prepare('minikube-poll.otlp.json')).r, state.DEFAULTS).map(w => w.name), ['service-j', 'service-f', 'service-k']);
  const { r: small, st } = run(prepare('savings-preview.otlp.json'));
  assert.deepStrictEqual(summary.pick(small, st).map(w => w.name), ['checkout-api', 'ledger-db', 'search-indexer']);
});

test('a short poll says what was read, adds the week-long run and nothing about data quality', () => {
  const { data, st, r } = run(prepare('minikube-poll.otlp.json'));
  assert.strictEqual(summary.provenance(r, st), 'From a 1-minute read of your cluster. Computed on your laptop. Nothing installed, nothing uploaded.');
  assert.strictEqual(summary.thin(r, st), true);
  const out = text(summary.markup(data, r, st));
  assert.ok(out.includes('Run it for a week for a full-month figure: savings-preview run --duration 168h'));
  assert.ok(out.includes(summary.headline(summary.figures(r))));
  assert.ok(!HEDGES.test(out), out.match(HEDGES));
  assert.ok(!out.includes('OOM'), 'no OOM line when nothing was killed');
});

test('provenance names the store and the window, and a single reading', () => {
  const r = { fidelity: { snapshot: false, source: 'datadog', start: 0, end: 2 * 86400, spanSeconds: 2 * 86400 } };
  assert.match(summary.provenance(r, state.DEFAULTS), /^From 2 days of your Datadog data\. /);
  assert.match(summary.provenance(r, Object.assign({}, state.DEFAULTS, { range: [0, 7200] })), /^From 2 hours of your Datadog data\. /);
  const poll = { fidelity: { snapshot: false, source: 'live polling', start: 0, end: 7200, spanSeconds: 7200 } };
  assert.match(summary.provenance(poll, state.DEFAULTS), /^From a 2-hour read of your cluster\. /);
  const one = { fidelity: { snapshot: true, source: 'live polling', start: 0, end: 15, spanSeconds: 15 } };
  assert.match(summary.provenance(one, state.DEFAULTS), /^From a single reading of your cluster\. /);
  const rolled = { fidelity: { snapshot: true, source: 'live polling', start: 0, end: 900, spanSeconds: 900, stepSeconds: 900, sourceStepSeconds: 15 } };
  assert.match(summary.provenance(rolled, state.DEFAULTS), /^From a read of your cluster under 15 minutes\. /);
  assert.strictEqual(summary.thin(r, state.DEFAULTS), true);
});

